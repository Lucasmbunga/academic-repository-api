package com.lucas.academicrepository.modules.user.entity;

import com.lucas.academicrepository.modules.academic.entity.Course;
import com.lucas.academicrepository.modules.academic.entity.Faculty;
import com.lucas.academicrepository.modules.academic.entity.Institution;
import com.lucas.academicrepository.modules.user.enums.Role;
import jakarta.persistence.*;
import lombok.AllArgsConstructor;
import lombok.Getter;
import lombok.NoArgsConstructor;
import lombok.Setter;
import org.springframework.security.core.GrantedAuthority;
import org.springframework.security.core.authority.SimpleGrantedAuthority;
import org.springframework.security.core.userdetails.UserDetails;

import java.time.LocalDateTime;
import java.util.Collection;
import java.util.List;

@Entity
@Table(name = "`user`")
@Getter
@Setter
@NoArgsConstructor
@AllArgsConstructor
public class User implements UserDetails {

    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    private Long id;

    @ManyToOne(fetch = FetchType.LAZY)
    @JoinColumn(name = "institution_id")
    private Institution institution;

    @ManyToOne(fetch = FetchType.LAZY)
    @JoinColumn(name = "faculty_id")
    private Faculty faculty;

    @ManyToOne(fetch = FetchType.LAZY)
    @JoinColumn(name = "course_id")
    private Course course;

    @Column(nullable = false, length = 100)
    private String name;

    @Column(nullable = false, unique = true, length = 50)
    private String email;

    @Column(name = "password", nullable = false)
    private String password;

    @Enumerated(EnumType.STRING)
    @Column(nullable = false, length = 30)
    private Role role;

    @Column(name = "is_active", nullable = false)
    private Boolean isActive;

    @Column(name = "created_at", updatable = false)
    private LocalDateTime createdAt;

    @PrePersist
    protected void onCreate() {
        this.createdAt = LocalDateTime.now();
        if (this.role == null) this.role = Role.VISITOR;
    }


    @Override
    public Collection<? extends GrantedAuthority> getAuthorities() {
        if(this.role==Role.ADMINISTRATOR){
            return List.of(new SimpleGrantedAuthority("ROLE_ADMINISTRATOR"),new SimpleGrantedAuthority("ROLE_MODERATOR"),new SimpleGrantedAuthority("ROLE_STUDENT"),new SimpleGrantedAuthority("ROLE_VISITOR"));
        } else if (this.role==Role.MODERATOR) {
            return List.of(new SimpleGrantedAuthority("ROLE_MODERATOR"),new SimpleGrantedAuthority("ROLE_STUDENT"),new SimpleGrantedAuthority("ROLE_VISITOR"));
        } else if(this.role==Role.STUDENT){
            return List.of(new SimpleGrantedAuthority("ROLE_STUDENT"),new SimpleGrantedAuthority("ROLE_VISITOR"));
        }
        else {
            return List.of(new SimpleGrantedAuthority("ROLE_VISITOR"));
        }
    }

    @Override
    public String getUsername() {
        return this.email;
    }

    @Override
    public boolean isAccountNonLocked() {
        return true;
    }

    @Override
    public boolean isCredentialsNonExpired() {
        return true;
    }

    @Override
    public boolean isAccountNonExpired() {
        return true;
    }

    @Override
    public boolean isEnabled() {
        return true;
    }

}